#!/usr/bin/env python3
"""Generate the GL trap the C++ component tests link on Linux and macOS.

    gl_trap_gen.py [--nm NM] -o gl_trap.cpp OBJECT...
    gl_trap_gen.py --self-test [--cxx CXX] [--nm NM]

Runs the toolchain's nm over the game's objects, collects every undefined
symbol that is a GL function (gl*, glu*), and writes a C++ file with one
definition per symbol. Each definition prints "GL call <name> while headless",
then a backtrace, and aborts. Linked into a headless test, it turns any GL call
the game makes into a failure that names the function, whatever the platform
would have done with a call and no context (spec 011, research R2).

The generated file includes no GL header, so its definitions conflict with no
declaration. With LTO the objects are bitcode and the trap is left out.

Exit status: 0 on success; 2 on a usage error or when nm cannot be run.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

GL_FUNCTION = re.compile(r"^glu?[A-Z][A-Za-z0-9_]*$")

HEADER = """\
// Generated by tests/component/gl_trap_gen.py from the game's objects.
// Do not edit. Each GL function the game imports, defined to fail loudly.

#include <execinfo.h>
#include <unistd.h>

#include <cstdio>
#include <cstdlib>

namespace {
[[noreturn]] void Trap(const char* name) {
  std::fprintf(stderr, "GL call %s while headless\\n", name);
  std::fflush(stderr);
  void* frames[64];
  const int count = backtrace(frames, 64);
  backtrace_symbols_fd(frames, count, STDERR_FILENO);
  std::abort();
}
}  // namespace

extern "C" {
"""

FOOTER = """}  // extern "C"
"""


def find_nm(requested):
    for candidate in ([requested] if requested else []) + [
            os.environ.get("NM", ""), "nm", "llvm-nm"]:
        if candidate and shutil.which(candidate):
            return shutil.which(candidate)
    return None


def undefined_symbols(nm, objects):
    """Every undefined symbol nm lists for the objects, as the linker sees it."""
    result = subprocess.run([nm, "-u"] + list(objects), check=True,
                            capture_output=True, text=True)
    names = set()
    for line in result.stdout.splitlines():
        line = line.strip()
        if not line or line.endswith(":"):  # blank, or a "file.o:" header
            continue
        names.add(line.split()[-1])
    return names


def gl_functions(symbols):
    """The GL functions among the symbols. Mach-O prefixes C names with '_'."""
    found = set()
    for name in symbols:
        if GL_FUNCTION.match(name):
            found.add(name)
        elif name.startswith("_") and GL_FUNCTION.match(name[1:]):
            found.add(name[1:])
    return sorted(found)


def render(functions):
    lines = [HEADER]
    for name in functions:
        lines.append("void %s();\n" % name)
        lines.append('void %s() { Trap("%s"); }\n' % (name, name))
    lines.append(FOOTER)
    return "".join(lines)


def generate(nm, objects, output):
    functions = gl_functions(undefined_symbols(nm, objects))
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(functions))
    return functions


def self_test(nm, cxx):
    """Build a fixture object that calls two GL functions and one other C
    function, run the generator over it and check what it wrote."""
    compiler = cxx or os.environ.get("CXX") or "c++"
    if not shutil.which(compiler):
        print("gl_trap_gen.py: no C++ compiler (%s) for the self-test" % compiler,
              file=sys.stderr)
        return 2
    with tempfile.TemporaryDirectory() as scratch:
        source = os.path.join(scratch, "fixture.cpp")
        obj = os.path.join(scratch, "fixture.o")
        output = os.path.join(scratch, "gl_trap.cpp")
        with open(source, "w", encoding="utf-8") as f:
            f.write('extern "C" void glLightfv(unsigned, unsigned, const float*);\n'
                    'extern "C" unsigned glGetError();\n'
                    'extern "C" int globalNotGL(int);\n'
                    'int fixture() { glLightfv(1, 2, nullptr);'
                    ' return static_cast<int>(glGetError()) + globalNotGL(3); }\n')
        subprocess.run([compiler, "-c", source, "-o", obj], check=True)
        functions = generate(nm, [obj], output)
        with open(output, encoding="utf-8") as f:
            text = f.read()
    problems = []
    if functions != ["glGetError", "glLightfv"]:
        problems.append("found %r, expected glGetError and glLightfv" % functions)
    for name in ("glGetError", "glLightfv"):
        if 'void %s() { Trap("%s"); }' % (name, name) not in text:
            problems.append("no trap for %s" % name)
    if "globalNotGL" in text:
        problems.append("a non-GL symbol was trapped")
    if '"GL call %s while headless' not in text:
        problems.append("the trap does not say what it caught")
    if "#include <GL" in text or "gl.h" in text:
        problems.append("the trap includes a GL header")
    for problem in problems:
        print("gl_trap_gen.py --self-test: " + problem, file=sys.stderr)
    if not problems:
        print("gl_trap_gen.py --self-test: ok")
    return 1 if problems else 0


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("objects", nargs="*")
    parser.add_argument("-o", "--output")
    parser.add_argument("--nm")
    parser.add_argument("--cxx")
    parser.add_argument("--self-test", action="store_true")
    try:
        args = parser.parse_args(argv)
    except SystemExit:
        return 2
    nm = find_nm(args.nm)
    if nm is None:
        print("gl_trap_gen.py: no nm to run", file=sys.stderr)
        return 2
    if args.self_test:
        return self_test(nm, args.cxx)
    if not args.output or not args.objects:
        parser.print_usage(sys.stderr)
        return 2
    try:
        functions = generate(nm, args.objects, args.output)
    except (OSError, subprocess.CalledProcessError) as error:
        print("gl_trap_gen.py: %s" % error, file=sys.stderr)
        return 2
    print("gl_trap_gen.py: %d GL functions trapped" % len(functions))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
