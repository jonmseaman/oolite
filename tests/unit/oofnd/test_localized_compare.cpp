/*	test_localized_compare.cpp
        oo::str::localizedCompare (oofnd/String.hpp) against
   -[NSString localizedCompare:] of GNUstep base 1.31.1.

        localized_compare_table.inc was generated by a throwaway Objective-C
   probe linked against gnustep-base: for every ordered pair of its words it
   recorded the sign of [words[i] localizedCompare:words[j]], with [NSLocale
   currentLocale] = kLocalizedCompareLocale. The words cover case, digits and
   version strings, punctuation and spaces, accents (precomposed and combining),
   ligatures, non-Latin scripts and the manifest categories OOOXZManager sorts.
        To extend it, rebuild that probe with more words and replace the table;
   do not hand-edit it.
*/

#include <algorithm>
#include <cstddef>
#include <vector>

#include <gtest/gtest.h>

#include "localized_compare_table.inc"
#include "oofnd/String.hpp"

namespace {

constexpr std::size_t kWords =
    sizeof(kLocalizedCompareWords) / sizeof(kLocalizedCompareWords[0]);
static_assert(sizeof(kLocalizedCompareSigns) /
                  sizeof(kLocalizedCompareSigns[0]) ==
              kWords);

int sign(int v) { return v < 0 ? -1 : (v > 0 ? 1 : 0); }

}  // namespace

TEST(localized_compare, every_pair_matches_gnustep) {
  EXPECT_TRUE(kWords >= 60u);
  std::size_t mismatches = 0;
  for (std::size_t i = 0; i < kWords; ++i) {
    for (std::size_t j = 0; j < kWords; ++j) {
      const int got = sign(oo::str::localizedCompare(kLocalizedCompareWords[i],
                                                     kLocalizedCompareWords[j],
                                                     kLocalizedCompareLocale));
      if (got != kLocalizedCompareSigns[i][j]) {
        ++mismatches;
        EXPECT_EQ(got, kLocalizedCompareSigns[i][j]);
      }
    }
  }
  EXPECT_EQ(mismatches, 0u);
}

TEST(localized_compare, readable_orderings) {
  // The case the manifest sort depends on: lower before upper, both before the
  // next letter.
  EXPECT_TRUE(oo::str::localizedCompare("a", "A", "en_US") < 0);
  EXPECT_TRUE(oo::str::localizedCompare("A", "b", "en_US") < 0);
  EXPECT_TRUE(oo::str::localizedCompare("Zz", "zz", "en_US") > 0);
  EXPECT_EQ(oo::str::localizedCompare("Ships", "Ships", "en_US"), 0);
  // ... where the literal order (compare) disagrees.
  EXPECT_TRUE(oo::str::compare("A", "b") < 0);
  EXPECT_TRUE(oo::str::compare("a", "B") > 0);
  EXPECT_TRUE(oo::str::localizedCompare("a", "B", "en_US") < 0);
}

TEST(localized_compare, sorting_matches_the_table) {
  // A sort by localizedCompare agrees with the order the GNUstep signs imply.
  std::vector<std::size_t> order(kWords);
  for (std::size_t i = 0; i < kWords; ++i) order[i] = i;
  std::stable_sort(
      order.begin(), order.end(), [](std::size_t x, std::size_t y) {
        return oo::str::localizedCompare(kLocalizedCompareWords[x],
                                         kLocalizedCompareWords[y],
                                         kLocalizedCompareLocale) < 0;
      });
  for (std::size_t k = 1; k < kWords; ++k) {
    EXPECT_TRUE(kLocalizedCompareSigns[order[k - 1]][order[k]] <= 0);
  }
}

TEST(localized_compare, default_locale_form_uses_icus_default) {
  for (std::size_t i = 0; i < kWords; ++i) {
    EXPECT_EQ(sign(oo::str::localizedCompare(kLocalizedCompareWords[i], "m")),
                sign(oo::str::localizedCompare(kLocalizedCompareWords[i], "m",
                                               uloc_getDefault())));
  }
}
